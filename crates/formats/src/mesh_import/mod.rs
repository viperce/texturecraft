#[derive(Clone, Debug, PartialEq)]
pub struct ImportedMesh {
    pub mesh: Mesh,
    pub report: MeshReport,
    /// Cameras of the file (glTF, FBX, COLLADA, USD), as orbit cameras around the mesh.
    pub cameras: Vec<texturecraft_core::Camera>,
    /// Materials with embedded textures (glTF PBR inputs; base color textures of the other
    /// formats), by material name.
    pub materials: Vec<MaterialTextures>,
}

/// Most entries of a zip package (usdz, an FBX with its textures).
pub(crate) const MAX_ZIP_ENTRIES: usize = 100_000;
/// Largest texture file read from a package or beside a mesh.
pub(crate) const MAX_TEXTURE_BYTES: u64 = 1 << 28;

/// Entry `name` of a zip package, at most `cap` bytes (None when missing, larger or unreadable).
pub(crate) fn zip_entry(zip: &mut zip::ZipArchive<std::io::Cursor<&[u8]>>, name: &str, cap: u64) -> Option<Vec<u8>> {
    use std::io::Read as _;
    let f = zip.by_name(name).ok()?;
    let mut data = Vec::new();
    f.take(cap + 1).read_to_end(&mut data).ok()?;
    (data.len() as u64 <= cap).then_some(data)
}

/// Cameras read from a file (at most [`MAX_CAMERAS`]).
pub(crate) const MAX_CAMERAS: usize = 64;

/// A camera as a file places it: world position, view direction, vertical field of view
/// (degrees, perspective) or half view height (orthographic).
pub(crate) struct RawCamera {
    pub name: String,
    pub eye: Vec3,
    pub forward: Vec3,
    pub fov: f32,
    pub ortho_half_height: Option<f32>,
}

impl RawCamera {
    /// A camera at the origin of `m` (local to world) looking along local `forward` with +Y
    /// up; `ortho_half_height` is in local units.
    pub fn placed(name: String, m: Mat4, forward: Vec3, fov: f32, ortho_half_height: Option<f32>) -> RawCamera {
        let scale = m.transform_vector3(Vec3::Y).length();
        RawCamera {
            name,
            eye: m.transform_point3(Vec3::ZERO),
            forward: m.transform_vector3(forward),
            fov,
            ortho_half_height: ortho_half_height.map(|h| h * scale),
        }
    }
}

/// Vertical field of view in degrees of a lens of `focal` length over a film `aperture` high
/// (same units).
pub(crate) fn lens_fov(focal: f32, aperture: f32) -> f32 {
    2.0 * (aperture / (2.0 * focal)).atan().to_degrees()
}

/// What the importer found and fixed, for the import dialog.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct MeshReport {
    pub triangles: usize,
    pub vertices: usize,
    pub materials: usize,
    /// The file had no UVs; they were generated by the automatic unwrap.
    pub uvs_generated: bool,
    /// Triangles with a UV outside 0..1.
    pub uv_out_of_range: usize,
    /// Overlapping texels / covered texels (512² per material).
    pub overlap_ratio: f32,
    pub zero_area_uv_triangles: usize,
    pub warnings: Vec<String>,
}

/// Geometry as read from a file, before normals, UVs and tangents are completed.
#[derive(Default)]
pub(crate) struct RawMesh {
    pub positions: Vec<Vec3>,
    /// Per-vertex normals for every vertex, or None to compute smooth (welded) normals.
    pub normals: Option<Vec<Vec3>>,
    /// Per-vertex UVs (glTF convention) for every vertex, or None to auto-unwrap.
    pub uvs: Option<Vec<Vec2>>,
    /// Per-vertex linear RGBA colors for every vertex, or None.
    pub colors: Option<Vec<Vec4>>,
    /// Triangles (vertex indices) per (material, part name); an empty part is unnamed.
    pub groups: Vec<(String, String, Vec<u32>)>,
    pub warnings: Vec<String>,
    pub cameras: Vec<RawCamera>,
    /// Materials whose base color is not plain white (glTF).
    pub base_colors: Vec<RawBaseColor>,
    /// Materials' other PBR inputs (glTF; base colors are in `base_colors`).
    pub materials: Vec<MaterialTextures>,
    /// Vertex pairs (smaller first) that [`RawMesh::polygon`] added to split polygons.
    pub diagonals: HashSet<(u32, u32)>,
}

/// A material's base color as a file gives it: the linear factor and the encoded texture.
pub(crate) struct RawBaseColor {
    pub material: String,
    pub factor: Vec4,
    pub image: Option<Vec<u8>>,
}

impl RawMesh {
    /// Triangle list of `material` in `part`, created on first use.
    pub fn group(&mut self, material: &str, part: &str) -> &mut Vec<u32> {
        let i = match self.groups.iter().position(|(m, p, _)| m == material && p == part) {
            Some(i) => i,
            None => {
                self.groups.push((material.to_string(), part.to_string(), Vec::new()));
                self.groups.len() - 1
            }
        };
        &mut self.groups[i].2
    }

    pub fn triangle_count(&self) -> usize {
        self.groups.iter().map(|(_, _, g)| g.len() / 3).sum()
    }

    /// Fan-triangulate polygon `corners` (vertex indices) into `material`'s triangles in `part`,
    /// remembering the diagonals so wireframes can show the polygon.
    pub fn polygon(&mut self, material: &str, part: &str, corners: &[u32]) {
        let Some((&first, rest)) = corners.split_first() else { return };
        let group = self.group(material, part);
        for w in rest.windows(2) {
            group.extend_from_slice(&[first, w[0], w[1]]);
        }
        for &v in rest.iter().skip(1).take(rest.len().saturating_sub(2)) {
            self.diagonals.insert((first.min(v), first.max(v)));
        }
    }
}

/// One polygon corner of a scene format (FBX, COLLADA), already in world space.
#[derive(Clone, Copy)]
pub(crate) struct Corner {
    pub p: Vec3,
    pub n: Option<Vec3>,
    pub uv: Option<Vec2>,
}

/// Collects polygons into a [`RawMesh`]: fan triangulation, one vertex per unique corner, and
/// normals / UVs kept only when every corner has them (else computed / unwrapped).
#[derive(Default)]
pub(crate) struct PolygonSink {
    /// Part name of the polygons that follow.
    pub part: String,
    raw: RawMesh,
    normals: Vec<Vec3>,
    uvs: Vec<Vec2>,
    missing_normals: bool,
    missing_uvs: bool,
    some_uvs: bool,
    ids: HashMap<[u32; 8], u32>,
    polygon: Vec<u32>,
    triangles: usize,
}

impl PolygonSink {
    pub fn polygon(&mut self, material: &str, corners: &[Corner]) -> Result<()> {
        if corners.len() < 3 {
            return Ok(());
        }
        check_triangles(self.triangles, corners.len() - 2)?;
        self.triangles += corners.len() - 2;
        self.polygon.clear();
        for c in corners {
            self.missing_normals |= c.n.is_none();
            self.missing_uvs |= c.uv.is_none();
            self.some_uvs |= c.uv.is_some();
            let (n, uv) = (c.n.unwrap_or_default(), c.uv.unwrap_or_default());
            let key = [c.p.x, c.p.y, c.p.z, n.x, n.y, n.z, uv.x, uv.y].map(f32::to_bits);
            let id = match self.ids.entry(key) {
                Entry::Occupied(e) => *e.get(),
                Entry::Vacant(e) => {
                    let id = self.raw.positions.len();
                    check_vertices(id + 1)?;
                    self.raw.positions.push(c.p);
                    self.normals.push(n);
                    self.uvs.push(uv);
                    *e.insert(id as u32)
                }
            };
            self.polygon.push(id);
        }
        self.raw.polygon(material, &self.part, &self.polygon);
        Ok(())
    }

    pub fn warn(&mut self, msg: String) {
        if !self.raw.warnings.contains(&msg) {
            self.raw.warnings.push(msg);
        }
    }

    pub fn finish(mut self) -> RawMesh {
        if self.missing_uvs && self.some_uvs {
            self.warn("some polygons have no UVs; the whole mesh was unwrapped automatically".into());
        }
        self.raw.normals = (!self.missing_normals).then_some(self.normals);
        self.raw.uvs = (!self.missing_uvs).then_some(self.uvs);
        self.raw
    }
}

/// Error unless `n` more triangles keep the total within [`MAX_TRIANGLES`].
pub(crate) fn check_triangles(have: usize, more: usize) -> Result<()> {
    if have.saturating_add(more) > MAX_TRIANGLES {
        return Err(FormatError::TooLarge(format!("mesh has more than {MAX_TRIANGLES} triangles")));
    }
    Ok(())
}

pub(crate) fn check_vertices(n: usize) -> Result<()> {
    if n > MAX_VERTICES {
        return Err(FormatError::TooLarge(format!("mesh has more than {MAX_VERTICES} vertices")));
    }
    Ok(())
}

fn extension(file_name: &str) -> String {
    std::path::Path::new(file_name).extension().and_then(|e| e.to_str()).unwrap_or_default().to_ascii_lowercase()
}

/// Import a mesh from bytes; the format comes from `file_name`'s extension. A `.gltf` must be
/// self-contained (see [`self_contained_mesh`]); OBJ material libraries are not read (usemtl
/// names are).
pub fn import_mesh_bytes(file_name: &str, bytes: &[u8]) -> Result<ImportedMesh> {
    finish(read(file_name, bytes)?)
}

/// Import a mesh file with the files it references next to it ([`read_mesh_file`]).
#[cfg(not(target_arch = "wasm32"))]
pub fn import_mesh(path: &std::path::Path) -> Result<ImportedMesh> {
    let f = read_mesh_file(path)?;
    let mut imported = import_mesh_bytes(&f.name, &f.bytes)?;
    imported.report.warnings.splice(0..0, f.warnings);
    Ok(imported)
}

/// Largest side of a base color texture kept for color-map bakes (larger ones are downscaled),
/// and the texel budget of one high poly's textures.
const BASE_COLOR_SIDE: u32 = 4096;
const BASE_COLOR_TEXELS: u64 = 1 << 26;

/// A high-poly mesh for baking and the base color of each of its materials (None: white).
#[derive(Clone, Debug, PartialEq)]
pub struct HighPolyMesh {
    pub mesh: Mesh,
    pub base_color: Vec<Option<BaseColor>>,
    /// Textures that could not be used.
    pub warnings: Vec<String>,
}

/// Import a high-poly (or cage) mesh for baking: like [`import_mesh_bytes`], but missing UVs stay
/// at 0 and no tangents are generated (bakers read positions, normals, colors, UVs and part
/// names), so million-triangle meshes import quickly. Base color factors and textures (glTF,
/// FBX media, usdz packages, and files [`self_contained_mesh`] folded in) come along for the
/// color map, textures downscaled to [`BASE_COLOR_SIDE`].
pub fn import_high_poly_bytes(file_name: &str, bytes: &[u8]) -> Result<HighPolyMesh> {
    let mut raw = read(file_name, bytes)?;
    let colors = std::mem::take(&mut raw.base_colors);
    let (mut mesh, mut warnings, uvs) = geometry(raw)?;
    let n = mesh.positions.len();
    mesh.uvs = uvs.filter(|uv| uv.len() == n && uv.iter().all(|v| v.is_finite())).unwrap_or_else(|| vec![Vec2::ZERO; n]);
    mesh.tangents = vec![Vec4::new(1.0, 0.0, 0.0, 1.0); n];
    mesh.validate()?;
    let mut budget = BASE_COLOR_TEXELS;
    let base_color = mesh
        .materials
        .iter()
        .map(|m| {
            let c = colors.iter().find(|c| c.material == *m)?;
            let (width, height, texels) = match c.image.as_deref().map(|b| decode_base_color(b, &mut budget)) {
                Some(Ok(t)) => t,
                Some(Err(e)) => {
                    warnings.push(format!("base color texture of {m}: {e}"));
                    (0, 0, Vec::new())
                }
                None => (0, 0, Vec::new()),
            };
            Some(BaseColor { factor: c.factor, width, height, texels })
        })
        .collect();
    Ok(HighPolyMesh { mesh, base_color, warnings })
}

/// Decode a base color texture to RGBA8, at most [`BASE_COLOR_SIDE`] per side, charging its
/// texels to `budget`.
fn decode_base_color(bytes: &[u8], budget: &mut u64) -> Result<(u32, u32, Vec<[u8; 4]>)> {
    let bad = |e: image::ImageError| FormatError::Malformed { kind: "image", msg: e.to_string() };
    let mut reader = image::ImageReader::new(std::io::Cursor::new(bytes)).with_guessed_format().map_err(|e| bad(e.into()))?;
    let mut limits = image::Limits::default();
    limits.max_image_width = Some(crate::MAX_IMAGE_SIZE);
    limits.max_image_height = Some(crate::MAX_IMAGE_SIZE);
    reader.limits(limits);
    let img = crate::guard("image", || reader.decode().map_err(bad))?;
    let img =
        if img.width().max(img.height()) > BASE_COLOR_SIDE { img.resize(BASE_COLOR_SIDE, BASE_COLOR_SIDE, image::imageops::FilterType::Triangle) } else { img };
    let rgba = img.into_rgba8();
    let (w, h) = rgba.dimensions();
    let texels = u64::from(w) * u64::from(h);
    if texels > *budget {
        return Err(FormatError::TooLarge(format!("the base color textures exceed {} megatexels", BASE_COLOR_TEXELS >> 20)));
    }
    *budget -= texels;
    Ok((w, h, rgba.pixels().map(|p| p.0).collect()))
}

fn read(file_name: &str, bytes: &[u8]) -> Result<RawMesh> {
    let mut raw = match extension(file_name).as_str() {
        "gltf" | "glb" => gltf::read(bytes)?,
        "fbx" => fbx::read(bytes)?,
        "dae" => dae::read(bytes)?,
        "usd" | "usda" | "usdc" | "usdz" => usd::read(file_name, bytes)?,
        "abc" => abc::read(bytes)?,
        "obj" => obj::read(bytes)?,
        "ply" => ply::read(bytes)?,
        "stl" => stl::read(bytes)?,
        other => return Err(FormatError::Unsupported(format!("mesh format \".{other}\" (supported: {})", MESH_EXTENSIONS.join(", ")))),
    };
    let stem = std::path::Path::new(file_name).file_stem().and_then(|s| s.to_str()).unwrap_or_default();
    for (material, part, _) in &mut raw.groups {
        if part.is_empty() {
            *part = if stem.is_empty() { material.clone() } else { stem.to_string() };
        }
    }
    Ok(raw)
}

/// Positions, submeshes (materials contiguous), normals and colors of a raw mesh, validated;
/// plus its warnings and UVs (the mesh's UVs and tangents are left empty).
fn geometry(raw: RawMesh) -> Result<(Mesh, Vec<String>, Option<Vec<Vec2>>)> {
    let RawMesh { positions, normals, uvs, colors, groups, warnings, diagonals, .. } = raw;
    check_vertices(positions.len())?;
    check_triangles(0, groups.iter().map(|(_, _, g)| g.len() / 3).sum())?;
    let mut mesh = Mesh { positions, ..Mesh::default() };
    let mut groups: Vec<(usize, String, Vec<u32>)> = groups
        .into_iter()
        .filter(|(_, _, g)| g.len() >= 3)
        .map(|(material, part, tris)| {
            let m = mesh.materials.iter().position(|x| *x == material).unwrap_or(mesh.materials.len());
            if m == mesh.materials.len() {
                mesh.materials.push(material);
            }
            (m, part, tris)
        })
        .collect();
    groups.sort_by_key(|g| g.0);
    for (material, name, tris) in groups {
        let start = u32::try_from(mesh.indices.len()).map_err(|_| FormatError::TooLarge("index count".into()))?;
        let count = (tris.len() / 3 * 3) as u32;
        mesh.indices.extend_from_slice(tris.get(..count as usize).unwrap_or_default());
        mesh.submeshes.push(SubMesh { name, material, start, count });
    }
    if mesh.indices.is_empty() {
        return Err(FormatError::Invalid("the file contains no triangles".into()));
    }
    if !diagonals.is_empty() {
        let diagonal = |a: u32, b: u32| diagonals.contains(&(a.min(b), a.max(b)));
        mesh.diagonals = mesh.indices.chunks_exact(3).map(|t| (0..3).map(|i| u8::from(diagonal(t[i], t[(i + 1) % 3])) << i).sum()).collect();
    }
    if let Some(bad) = mesh.indices.iter().find(|i| **i as usize >= mesh.positions.len()) {
        return Err(FormatError::Invalid(format!("vertex index {bad} out of range ({} vertices)", mesh.positions.len())));
    }
    if mesh.positions.iter().any(|p| !p.is_finite()) {
        return Err(FormatError::Invalid("the mesh has non-finite vertex positions".into()));
    }
    if all_triangles_degenerate(&mesh) {
        return Err(FormatError::Invalid("every triangle of the mesh is degenerate (zero area)".into()));
    }
    mesh.normals = match normals {
        Some(n) if n.len() == mesh.positions.len() => n.into_iter().map(|v| v.try_normalize().unwrap_or(Vec3::Y)).collect(),
        _ => smooth_normals(&mesh),
    };
    if let Some(c) = colors.filter(|c| c.len() == mesh.positions.len()) {
        mesh.colors = c.into_iter().map(|v| if v.is_finite() { v.clamp(Vec4::ZERO, Vec4::ONE) } else { Vec4::ONE }).collect();
    }
    Ok((mesh, warnings, uvs))
}

/// Complete a raw mesh: submeshes, normals, UVs, tangents, validation and the report.
pub(crate) fn finish(mut raw: RawMesh) -> Result<ImportedMesh> {
    let mut raw_cameras = std::mem::take(&mut raw.cameras);
    raw_cameras.truncate(MAX_CAMERAS);
    let materials = material_textures(std::mem::take(&mut raw.materials), std::mem::take(&mut raw.base_colors));
    let (mut mesh, mut warnings, uvs) = geometry(raw)?;
    let uvs_generated = match uvs {
        Some(uv) if uv.len() == mesh.positions.len() => {
            if uv.iter().any(|v| !v.is_finite()) {
                warnings.push("non-finite UVs were replaced with 0".into());
            }
            mesh.uvs = uv.into_iter().map(|v| if v.is_finite() { v } else { Vec2::ZERO }).collect();
            mesh.compute_tangents();
            false
        }
        _ => {
            let charts = auto_unwrap(&mut mesh, UNWRAP_PADDING, UNWRAP_RESOLUTION)?;
            warnings.push(format!("the mesh has no UVs; generated an automatic unwrap with {charts} charts"));
            true
        }
    };
    mesh.validate()?;
    let report = report(&mesh, uvs_generated, warnings);
    let cameras = orbit_cameras(&raw_cameras, &mesh);
    Ok(ImportedMesh { mesh, report, cameras, materials })
}

/// `materials` with their base colors, keeping those that have a texture.
fn material_textures(mut materials: Vec<MaterialTextures>, base_colors: Vec<RawBaseColor>) -> Vec<MaterialTextures> {
    for c in base_colors {
        let i = match materials.iter().position(|m| m.material == c.material) {
            Some(i) => i,
            None => {
                materials.push(MaterialTextures { material: c.material.clone(), ..MaterialTextures::default() });
                materials.len() - 1
            }
        };
        if let Some(m) = materials.get_mut(i) {
            m.base_color = Some(c.factor);
            m.base_color_image = c.image;
        }
    }
    materials.retain(MaterialTextures::has_images);
    materials
}

/// File cameras as orbit cameras: the target is where the view axis passes the mesh center
/// (at least a tenth of the mesh size ahead). shortcut: camera roll is dropped (orbit cameras
/// keep +Y up); keep a free camera transform if imported rolls matter.
fn orbit_cameras(raw: &[RawCamera], mesh: &Mesh) -> Vec<texturecraft_core::Camera> {
    let (lo, hi) = mesh.bounds();
    let (center, radius) = ((lo + hi) * 0.5, ((hi - lo).length() * 0.5).max(1e-3));
    raw.iter()
        .filter(|c| c.eye.is_finite() && c.forward.is_finite())
        .filter_map(|c| {
            let f = c.forward.try_normalize()?;
            let distance = (center - c.eye).dot(f).max(radius * 0.1);
            let target = c.eye + f * distance;
            let fov = match c.ortho_half_height {
                Some(h) => 2.0 * (h.abs() / distance).atan().to_degrees(),
                None => c.fov,
            };
            let fov = if fov.is_finite() { fov.clamp(5.0, 150.0) } else { 40.0 };
            Some(texturecraft_core::Camera {
                name: c.name.clone(),
                target: target.to_array(),
                yaw: (-f.x).atan2(-f.z),
                pitch: (-f.y).clamp(-1.0, 1.0).asin().clamp(-89f32.to_radians(), 89f32.to_radians()),
                distance,
                fov,
                ortho: c.ortho_half_height.is_some(),
            })
        })
        .collect()
}

/// Area-weighted smooth normals over welded positions (UV seams do not split shading).
fn smooth_normals(mesh: &Mesh) -> Vec<Vec3> {
    let weld = weld_ids(&mesh.positions);
    let mut acc = vec![Vec3::ZERO; mesh.positions.len()];
    for t in mesh.indices.chunks_exact(3) {
        let p = |i: u32| mesh.positions.get(i as usize).copied().unwrap_or_default();
        let face = (p(t[1]) - p(t[0])).cross(p(t[2]) - p(t[0]));
        for v in t {
            if let Some(a) = weld.get(*v as usize).and_then(|w| acc.get_mut(*w as usize)) {
                *a += face;
            }
        }
    }
    weld.iter().map(|w| acc.get(*w as usize).and_then(|n| n.try_normalize()).unwrap_or(Vec3::Y)).collect()
}

/// Inspects `mesh` and generates its UV report (overlaps, out-of-range UVs, warnings).
pub fn mesh_report(mesh: &Mesh) -> MeshReport {
    report(mesh, false, Vec::new())
}

fn report(mesh: &Mesh, uvs_generated: bool, mut warnings: Vec<String>) -> MeshReport {
    let (mut out_of_range, mut zero_area) = (0, 0);
    for t in 0..mesh.triangle_count() {
        let Some(vs) = mesh.tri(t) else { continue };
        let uv = vs.map(|v| mesh.uvs.get(v).copied().unwrap_or_default());
        if uv.iter().any(|u| u.min_element() < -1e-4 || u.max_element() > 1.0 + 1e-4) {
            out_of_range += 1;
        }
        if (uv[1] - uv[0]).perp_dot(uv[2] - uv[0]).abs() < 1e-12 {
            zero_area += 1;
        }
    }
    let (mut overlaps, mut covered) = (0u64, 0u64);
    for m in 0..mesh.materials.len() {
        let g = UvGBuffer::new(mesh, m, REPORT_RESOLUTION, REPORT_RESOLUTION);
        overlaps += g.overlaps as u64;
        covered += g.covered_count() as u64;
    }
    let overlap_ratio = if covered == 0 { 0.0 } else { overlaps as f32 / covered as f32 };
    if out_of_range > 0 {
        warnings.push(format!("{out_of_range} triangles have UVs outside 0..1 (painted as UDIM tiles when they lie in tiles 1001 and up)"));
    }
    if overlap_ratio > 0.01 {
        warnings.push(format!("{:.1}% of the UV layout overlaps; painting there affects several places at once", overlap_ratio * 100.0));
    }
    if zero_area > 0 {
        warnings.push(format!("{zero_area} triangles have zero UV area and cannot be painted"));
    }
    MeshReport {
        triangles: mesh.triangle_count(),
        vertices: mesh.vertex_count(),
        materials: mesh.materials.len(),
        uvs_generated,
        uv_out_of_range: out_of_range,
        overlap_ratio,
        zero_area_uv_triangles: zero_area,
        warnings,
    }
}
